# variables y tipos de datos

my_name = 'UrielSA' # str = string - texto
universidad = 'HyBridge' # str = string - texto
soy = 'Estudiante actual' # str = string - texto
edad = 22 # int - numero entero
altura = 1.80 # float - numero decimal
soy_estudiante = True # bool - si es verdadero
soy_estudiante2 = False # bool - si es falso

'''
Aqui mostrare unos ejemplos como podemos imprimir nuestro
texto en la consola
'''

print(my_name) # se imprime el valor de la variable nombre
print(universidad) # se imprime el valor de la variable universidad
print(soy) # se imprime el valor de la variable soy
print(edad) # se imprime el valor de la variable edad
print(altura) # se imprime el valor de la variable altura
print(soy_estudiante) # se imprime el valor de la variable soy_estudiante
print(soy_estudiante2) # se imprime el valor de la variable soy_estudiante2

# aqui podemos mostrar que tipo de dato esta utilizando cada variable

print(type(my_name))
print(type(universidad))
print(type(soy))
print(type(edad))
print(type(altura))
print(type(soy_estudiante))
print(type(soy_estudiante2))

# si quieres mas limpio el dato y no salga el mensaje class podemos hacerlo asi

print(type(my_name).__name__)
print(type(edad).__name__)
print(type(altura).__name__)
print(type(soy_estudiante).__name__)
print(type(soy_estudiante2).__name__)

